/* صراحة — تصحيح الإملاء وتوحيد أسلوب الكتابة عشان محد يعرف مين كتب */
/* ============ التصحيح وتوحيد الأسلوب ============ */
const Polish = (() => {
  const L = '\\u0621-\\u063A\\u0641-\\u064A';
  const reWord = new RegExp(`[${L}]+`, 'g');
  const reAr = new RegExp(`[${L}]`);
  const NB = `(?=[^${L}]|$)`;
  const LAUGH = '';
  // الهمزة في آخر الكلمة تبقى (عشان «ابدأ» ما تصير «أبدا»)
  const skel = w => w.replace(/[أإآ](?!$)/g, 'ا').replace(/ة$/, 'ه').replace(/ى$/, 'ي');

  // قاموس: الشكل الصحيح ← يتطابق مع أي كتابة لها نفس الهيكل (بدون همزات/ة/ى)
  const DICT = new Map();
  const add = (words, f) => words.trim().split(/\s+/).forEach(w => DICT.set(skel(w), { w, ...f }));
  add(`أحب أكره أحس أعرف أعتقد أظن أشوف أقول أقدر أبي أبغى أتمنى أتوقع أخاف أفكر أصدق أكيد أبد أبدا أول أولا
       أحيانا أصلا أيضا أمس آسف آخر أحلى أجمل أطيب أحسن أفضل أكثر أقل أسوأ أغلب أسلوب أخلاق أهل أخت أخو أخوي
       أختي أبوي أمي أم أصحاب أصدقاء أمور أشياء أسرار أيام أفكار أخطاء أحلام إنسان إحساس أدري
       ابتسامة اهتمام احترام اختلاف انطباع اعتذار اتصال امتحان انتظار اثنين اسم استهبال اجتماعي انتباه استغلال`, { suf: true });
  add(`أنا أنت أنتي أنتم أنتو أب أهلا إذا إلا حتى متى أخرى أولى`, {});
  add(`أو`, { nopre: true });
  add(`صراحة حلوة مرة شخصية طيبة جميلة حياة فكرة مشكلة علاقة صداقة ثقة نفسية عصبية حساسة ذكية قوية ضعيفة لطيفة
       كريمة عنيدة مغرورة متكبرة مرحة خفيفة ثقيلة نصيحة ملاحظة ساعة حاجة سنة لحظة سالفة طاقة بداية نهاية عادة
       عادية طبيعية واضحة صادقة كذابة أنانية اجتماعية هدية فرصة تجربة مدرسة جامعة شلة زعلانة مبسوطة رهيبة
       مزاجية دلوعة عسولة مهمة صعبة سهلة غريبة بعيدة كبيرة صغيرة زينة حنونة مميزة مختلفة محترمة مزعجة مضحكة
       وناسة نية إنسانة غبية ثانية`, { ta: true });

  // أخطاء مشهورة (تطابق حرفي)
  const EX = new Map(Object.entries({
    'لاكن': 'لكن', 'لاكنك': 'لكنك', 'لاكني': 'لكني', 'لاكنه': 'لكنه', 'لاكنها': 'لكنها', 'لاكنهم': 'لكنهم',
    'هاذا': 'هذا', 'هاذي': 'هذي', 'هاذه': 'هذه', 'هذى': 'هذي', 'هاذى': 'هذي', 'ذالك': 'ذلك',
    'هاكذا': 'هكذا', 'هكذى': 'هكذا', 'فى': 'في', 'الى': 'إلى', 'اللة': 'الله', 'انته': 'أنته',
    'انشالله': 'إن شاء الله', 'انشاالله': 'إن شاء الله', 'انشاءالله': 'إن شاء الله', 'إنشاءالله': 'إن شاء الله',
    'إنشالله': 'إن شاء الله', 'انشاللة': 'إن شاء الله',
    'ماشالله': 'ما شاء الله', 'ماشاءالله': 'ما شاء الله', 'ماشاالله': 'ما شاء الله', 'مشالله': 'ما شاء الله',
    'الحمدالله': 'الحمد لله', 'الحمدلله': 'الحمد لله', 'باذن': 'بإذن', 'بأذن': 'بإذن',
    'لان': 'لأن', 'لانه': 'لأنه', 'لانك': 'لأنك', 'لاني': 'لأني', 'لانها': 'لأنها', 'لانهم': 'لأنهم', 'لانكم': 'لأنكم', 'لاننا': 'لأننا',
    'للاسف': 'للأسف', 'للإسف': 'للأسف', 'للأسف': 'للأسف', 'أسف': 'أسف', 'شئ': 'شيء', 'شيئ': 'شيء',
    'مسئول': 'مسؤول', 'مسوول': 'مسؤول', 'مسئوليه': 'مسؤولية', 'مسؤوليه': 'مسؤولية', 'مسئولية': 'مسؤولية',
    'سوال': 'سؤال', 'اسئله': 'أسئلة', 'اسئلة': 'أسئلة',
    'عضيم': 'عظيم', 'عضيمه': 'عظيمة', 'عضيمة': 'عظيمة', 'نضيف': 'نظيف', 'نضيفه': 'نظيفة', 'نضيفة': 'نظيفة',
    'ضلم': 'ظلم', 'ضالم': 'ظالم', 'ضالمه': 'ظالمة', 'ضالمة': 'ظالمة', 'ضروف': 'ظروف', 'لحضه': 'لحظة', 'لحضة': 'لحظة',
    'ملاحضه': 'ملاحظة', 'ملاحضة': 'ملاحظة', 'منضر': 'منظر', 'حافض': 'حافظ', 'انتضر': 'انتظر',
    'مضلوم': 'مظلوم', 'مضلومه': 'مظلومة', 'نضره': 'نظره', 'نضرة': 'نظرة',
    'علشان': 'عشان', 'علشانك': 'عشانك', 'اوكي': 'أوكي', 'اوكيه': 'أوكي', 'اوك': 'أوكي',
    'رايع': 'رائع', 'رايعه': 'رائعة', 'رايعة': 'رائعة', 'رائعه': 'رائعة',
    'هاديه': 'هادئة', 'هادئه': 'هادئة', 'هادية': 'هادئة', 'مؤدبه': 'مؤدبة',
    'راي': 'رأي', 'رايي': 'رأيي', 'مافي': 'ما في', 'مادري': 'ما أدري', 'ماعرف': 'ما أعرف',
    'ماعندي': 'ما عندي', 'ماعندك': 'ما عندك', 'ماعنده': 'ما عنده', 'ماعندها': 'ما عندها', 'ماعندهم': 'ما عندهم'
  }));

  const PRE = ['وال', 'فال', 'بال', 'لل', 'ال', 'و', 'ف', 'ب', 'ل'];
  const SUF = ['كم', 'هم', 'ها', 'نا', 'ك', 'ه', 'ي'];
  const preOK = (d, p) => !p || (!d.nopre && ((p !== 'ب' && p !== 'ل') || d.ta));
  function lookup(t, p) {
    const ex = EX.get(t);
    if (ex) return (p === 'ب' || p === 'ل') ? null : ex;
    let d = DICT.get(skel(t));
    if (d && preOK(d, p)) return d.w;
    for (const s of SUF) {
      if (t.length - s.length < 2 || !t.endsWith(s)) continue;
      const base = t.slice(0, -s.length);
      d = DICT.get(skel(base));
      if (d && d.suf && preOK(d, p)) return d.w + s;
      const e2 = EX.get(base);
      if (e2 && p !== 'ب' && p !== 'ل' && /^[^\sةى]+$/.test(e2)) return e2 + s;
    }
    return null;
  }
  function fixWord(t) {
    if (t.length < 2) return t;
    let r = lookup(t, '');
    if (r) return r;
    for (const p of PRE) {
      if (t.length - p.length < 2 || !t.startsWith(p)) continue;
      r = lookup(t.slice(p.length), p);
      if (r) return p + r;
    }
    return t;
  }
  const isLaugh = w => /^(?:[هخ]{2,}[عا]*|(?:ها){2,}ه?|ه+ع+)$/.test(w);

  const EMOJI = /[\p{Extended_Pictographic}\u{1F1E6}-\u{1F1FF}\u{1F3FB}-\u{1F3FF}‍︎️⃣]/gu;
  const EMOTICON = /(^|\s)(?:[:;=xX][-'^]?[)(\]\[DPpOo3*|\\/@$]+|[)(\]\[]+[-'^]?[:;=]|<\/?3+|\^[_.-]?\^|[Tt][_.][Tt]|-_-|>_<|[oO]_[oO])(?=\s|$)/g;
  const endP = s => /[.!؟?…]$/.test(s) ? s : s.replace(/[\s،,؛;:\-]+$/, '') + '.';

  function polish(input) {
    let t = String(input || '').normalize('NFKC').replace(/\r\n?/g, '\n');
    // تشكيل، تطويل، محارف مخفية
    t = t.replace(/[ؐ-ًؚ-ٰٟۖ-ۭـ]/g, '');
    t = t.replace(/[​-‏‪-‮⁠-⁩﻿­]/g, '');
    // حروف وأرقام بأشكال مختلفة
    t = t.replace(/[کڪ]/g, 'ك').replace(/[یێ]/g, 'ي').replace(/[ہھ]/g, 'ه').replace(/ۀ/g, 'ة').replace(/ٱ/g, 'ا');
    t = t.replace(/[٠-٩]/g, d => d.charCodeAt(0) - 0x660).replace(/[۰-۹]/g, d => d.charCodeAt(0) - 0x6F0);
    // إيموجي ووجوه وزخارف
    t = t.replace(EMOJI, ' ').replace(EMOTICON, '$1').replace(/[♡♥❤☺☹✿❀✨★☆•●◦▪~*_|^]+/g, ' ');
    const ar = reAr.test(t);
    // الضحك بكل أشكاله ← ههه
    t = t.replace(reWord, w => isLaugh(w) ? LAUGH : w);
    if (ar) t = t.replace(/\b(?:h{2,}|(?:ha){2,}h?|(?:he){2,}|lo+l|lmf?ao+|xd+)\b/gi, LAUGH);
    t = t.replace(new RegExp(`${LAUGH}(?:[\\s.,،!؟?]*${LAUGH})+`, 'g'), LAUGH);
    // التمطيط: حلووووه ← حلوه
    t = t.replace(new RegExp(`([${L}])\\1{2,}`, 'g'), (m, c) => c === 'ل' ? 'لل' : c);
    t = t.replace(/([a-z])\1{2,}/gi, '$1$1');
    t = t.replace(new RegExp(`(^|[^${L}])ماا(?=[${L}]{2})`, 'g'), '$1ما ا');
    // النفي الملصوق: ماتفهم ← ما تفهم
    t = t.replace(new RegExp(`(^|[^${L}])(و?)ما(?=[تين][${L}]{3}${NB})`, 'g'), '$1$2ما ');
    t = t.replace(new RegExp(`اا${NB}`, 'g'), 'ا');
    // عبارات مشهورة
    t = t.replace(new RegExp(`(^|[^${L}])[اأإ]ن\\s*شاء?\\s*الل[هة]${NB}`, 'g'), '$1إن شاء الله');
    t = t.replace(new RegExp(`(^|[^${L}])ما\\s*شاء?\\s*الل[هة]${NB}`, 'g'), '$1ما شاء الله');
    t = t.replace(new RegExp(`(^|[^${L}])الحمد\\s*(?:لل|الل)[هة]${NB}`, 'g'), '$1الحمد لله');
    // واو العطف المفصولة: "و انا" ← "وأنا"
    t = t.replace(new RegExp(`(^|\\s)و\\s+(?=[${L}])`, 'g'), '$1و');
    // تصحيح الكلمات
    t = t.replace(reWord, fixWord);
    // علامات الترقيم
    t = t.replace(/[“”„‟″"«»]/g, '"').replace(/[‘’‚‛′`]/g, "'").replace(/[–—]/g, '-');
    if (ar) t = t.replace(/\?/g, '؟').replace(/,/g, '،').replace(/;/g, '؛');
    t = t.replace(/[!؟?]{2,}/g, m => /[؟?]/.test(m) ? (ar ? '؟' : '?') : '!');
    t = t.replace(/(?:\.{2,}|…)[.…]*/g, '…');
    t = t.replace(/([،,؛;:])(?:\s*[،,؛;:])+/g, '$1');
    t = t.replace(/[،,؛;:]\s*([.!؟?…])/g, '$1');
    t = t.replace(/[ \t ]+/g, ' ');
    t = t.replace(/ ([،,؛;:.!؟?…])/g, '$1');
    t = t.replace(/([،,؛;:!؟?…])(?=[^\s\d.،,؛;:!؟?…)\]"'])/g, '$1 ');
    t = t.replace(/\.(?=[^\s\d.،,؛;:!؟?…)\]"'])/g, '. ');
    // الأسطر تصير جمل متتالية
    const lines = t.split('\n').map(s => s.trim().replace(/^[\s.،,؛;:!؟?…\-]+/, '').trim()).filter(Boolean);
    t = lines.map(endP).join(' ');
    t = t.replace(/ {2,}/g, ' ').trim();
    if (!/[\p{L}\p{N}]/u.test(t)) return '';
    return endP(t).replace(new RegExp(LAUGH, 'g'), 'ههه');
  }

  // ألفاظ جارحة (سب وشتم) — تمنع الإرسال
  const BAD = new Set(`كلب كلبه حمار حماره حيوان حيوانه زق خرا خره قحبه قحب شرموط شرموطه منيوك منيك زب كس طيز تفو
    يلعن ملعون ملعونه لعنه حقير حقيره واطي واطيه عاهر عاهره داعر داعره ديوث زباله حثاله نذل نذله سافل سافله`.split(/\s+/));
  function isRude(text) {
    const norm = text.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي');
    for (const w of norm.match(reWord) || []) {
      if (BAD.has(w)) return true;
      for (const p of ['يال', 'وال', 'يا', 'ال', 'و']) if (w.startsWith(p) && BAD.has(w.slice(p.length))) return true;
      if (w.endsWith('ين') && BAD.has(w.slice(0, -2))) return true;
    }
    return false;
  }
  return { polish, isRude };
})();
window.SarahaTest = { polish: Polish.polish, isRude: Polish.isRude };
